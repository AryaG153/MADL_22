# Experiment: Testing and Deployment of Flutter App

### Aim

To develop and test a Flutter application using DartPad and demonstrate its deployment on Android.

### Tools

DartPad, Flutter/Dart, Web Browser, Android Smartphone.

### Theory

Flutter is a UI framework by Google that uses Dart and provides reusable widgets for building interactive applications. DartPad allows Flutter apps to be developed and tested online without local installation.

### Procedure

1. Open DartPad and select **Flutter**.
2. Create the app using `MaterialApp` and `Scaffold`.
3. Add widgets such as `AppBar`, `Drawer`, `Card`, `GridView`, `Buttons`, `Switch`, and `BottomNavigationBar`.
4. Use `StatefulWidget` and `setState()` for interactivity.
5. Run and test navigation, buttons, notifications, and progress tracking.
6. Build the project as an APK using a cloud Flutter environment and install it on an Android phone.

### Result

The **Student Hub** Flutter application was successfully developed and tested. Its widgets, navigation, and interactive features worked correctly.

### Conclusion

The Flutter application was successfully tested using DartPad and can be deployed on Android using a cloud-based Flutter build environment.
